"""Large page data lives in its own repository, so this one stays small.

The archive pages (html/archive_first_look.html, html/archive_density.html) read their large data files from
https://pahbs.github.io/csda_summaries_data/, a second public repository published by GitHub Pages. Same site as these
pages, so the browser reads the files directly. Each push replaces that repository's single commit: it holds one copy of
the data, never a growing history. The full history of the data stays on ADAPT, in the stores the builders read.

Builders write into a working copy of that repository (DATA_REPO); after a refresh:

    python lib/data_repo.py push "what changed"
"""
from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DATA_REPO = Path(os.environ.get("CSDA_DATA_REPO", REPO.parent / "csda_summaries_data"))
DATA_URL = "https://pahbs.github.io/csda_summaries_data/"
REMOTE = "git@github.com:pahbs/csda_summaries_data.git"

README = """# CSDA Summaries: page data

Data files read by the archive pages of [CSDA Summaries](https://github.com/pahbs/csda_summaries):
the [Vendor Archive First Look](https://pahbs.github.io/csda_summaries/html/archive_first_look.html) and the
[Vendor Archive Density Dashboard](https://pahbs.github.io/csda_summaries/html/archive_density.html).

Generated by `lib/archive_dashboard.py` and `lib/archive_density.py` in that repository, and replaced on each refresh
(this repository keeps a single commit). Do not edit by hand.

| Folder | Contents |
|---|---|
| `archive_first_look/` | One file per vendor constellation tab; `fp/<tab>/<site>.json` holds each site's acquisition footprints |
| `archive_density/` | One file per constellation: monthly counts per map cell |
"""


def folder(name: str) -> Path:
    """A folder in the working copy, created (with the repository itself) if needed."""
    init()
    path = DATA_REPO / name
    path.mkdir(parents=True, exist_ok=True)
    return path


def _git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(DATA_REPO), *args], check=True, capture_output=True, text=True).stdout


def init() -> None:
    if (DATA_REPO / ".git").exists():
        return
    DATA_REPO.mkdir(parents=True, exist_ok=True)
    _git("init", "-q", "-b", "main")
    _git("remote", "add", "origin", REMOTE)
    (DATA_REPO / "README.md").write_text(README, encoding="utf-8")
    (DATA_REPO / ".nojekyll").write_text("", encoding="utf-8")   # serve the files as they are, without a Jekyll build


def push(message: str = "Page data") -> None:
    """Replace the published data with what is in the working copy: one commit, force-pushed."""
    init()
    _git("checkout", "-q", "--orphan", "publish")
    _git("add", "-A")
    _git("commit", "-q", "-m", message)
    if "main" in _git("branch", "--list", "main"):
        _git("branch", "-q", "-D", "main")
    _git("branch", "-q", "-m", "main")
    subprocess.run(["git", "-C", str(DATA_REPO), "push", "-q", "-f", "origin", "main"], check=True)
    _git("gc", "-q", "--prune=now")   # drop the replaced commit locally too
    print(f"pushed to {REMOTE}; live at {DATA_URL} after the Pages build")


if __name__ == "__main__":
    if sys.argv[1:2] == ["push"]:
        push(" ".join(sys.argv[2:]) or "Page data")
    else:
        sys.exit("usage: python lib/data_repo.py push \"what changed\"")
